#!/usr/bin/env bash
#
# Vendor OpenSeadragon into assets/vendor/ at a pinned version.
#
# This is the ONLY place the OpenSeadragon version is chosen. Bumping it is a
# deliberate PR: change OSD_VERSION, re-run `areas/access/cpe/image-viewer/scripts/vendor-osd.sh`, review
# the regenerated VENDOR.lock manifest, and commit. The vendored files are
# committed to git (deterministic builds, offline demos) — see
# dsp-incubator cpe/docs/adr/0010-openseadragon-integration.md and this crate's README.
#
# A file this script adds under assets/vendor/ needs a row in the `ASSETS` table
# in src/lib.rs: `cargo test -p cpe-image-viewer` fails for a file that has none.
#
# Provenance: files come from the official npm package mirrored by jsDelivr.
# Every downloaded file's SHA-256 is written to assets/vendor/VENDOR.lock so a
# re-vendor of the same version is verifiable and a tampered download is caught.
set -euo pipefail

OSD_VERSION="6.0.2"

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
vendor_dir="${script_dir}/../assets/vendor"
images_dir="${vendor_dir}/images"
base="https://cdn.jsdelivr.net/npm/openseadragon@${OSD_VERSION}/build/openseadragon"

# The 10 navigation controls, each with 4 states. OSD's default `prefixUrl`
# resolves exactly these filenames; the wrapper points `prefixUrl` at images/.
controls=(button flip fullpage home next previous rotateleft rotateright zoomin zoomout)
states=(rest hover pressed grouphover)

mkdir -p "${images_dir}"

fetch() { # url dest
  echo "  ↓ $2"
  curl -fsSL "$1" -o "$2"
}

echo "Vendoring OpenSeadragon ${OSD_VERSION} → ${vendor_dir}"
fetch "${base}/openseadragon.min.js" "${vendor_dir}/openseadragon.min.js"
for c in "${controls[@]}"; do
  for s in "${states[@]}"; do
    fetch "${base}/images/${c}_${s}.png" "${images_dir}/${c}_${s}.png"
  done
done

# Write a lock manifest: version + a sha256 of every vendored file (paths
# relative to assets/vendor/). Deterministic ordering so diffs are readable.
lock="${vendor_dir}/VENDOR.lock"
{
  echo "# OpenSeadragon vendored assets — generated by scripts/vendor-osd.sh"
  echo "# Do not edit by hand. Re-run the vendor recipe to regenerate."
  echo "version = ${OSD_VERSION}"
  echo "source  = ${base}"
  echo ""
  ( cd "${vendor_dir}" && find . -type f ! -name VENDOR.lock | sort | while read -r f; do
      sha="$(shasum -a 256 "$f" | cut -d' ' -f1)"
      printf '%s  %s\n' "$sha" "${f#./}"
    done )
} > "${lock}"

echo "Wrote ${lock}:"
sed -n '1,6p' "${lock}"
echo "  … ($(grep -c '  ' "${lock}") files hashed)"
