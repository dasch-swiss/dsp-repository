//! The store file: a header comment, a blank line, then one multi-row `INSERT` per table, each
//! followed by a blank line.
//!
//! One statement per table keeps `cpe_store::db::open_project_db`'s load linear, and the layout is
//! fixed byte for byte, so that the files of two snapshots differ only where their rows do.

use cpe_core::remodel::Remodel;

use crate::store::{
    AnnotationLinkRow, AnnotationLinkTargetRow, AnnotationRow, CompoundPartRow, ListNodeLabelRow, ListNodeRow, ListRow,
    PropertyRow, Real, RepresentationRow, ResourceRow, Store, Table,
};

/// A table that was to be written has no row, and a multi-row `INSERT` has no empty form.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("table {} has no row", .0.name())]
pub struct EmptyTable(pub Table);

/// The whole store file of the project `mapping` describes, under `header`: [`to_sql_tables`]
/// of every table.
pub fn to_sql(store: &Store, mapping: &Remodel, header: &str) -> Result<String, EmptyTable> {
    to_sql_tables(store, mapping, header, &Table::ALL)
}

/// `header` and the `INSERT`s of `tables` only, in the file's order whatever order `tables`
/// has. It is public for the crate's integration tests, which load a store table by table.
///
/// A table that has a row is written. One that has none is refused where the mapping has the
/// block that fills it, and gets no statement where it has not: the list tables go with a
/// `list`, `representations` with `images`, `compound_parts` with a `member-of`, and the
/// annotation tables with `annotations`. `resources` and `properties` are never empty.
pub fn to_sql_tables(store: &Store, mapping: &Remodel, header: &str, tables: &[Table]) -> Result<String, EmptyTable> {
    let mut written = Vec::new();
    for table in Table::ALL {
        if !tables.contains(&table) {
            continue;
        }
        if store.row_count(table) > 0 {
            written.push(table);
        } else if has_block(mapping, table) {
            return Err(EmptyTable(table));
        }
    }
    Ok(write(store, header, &written))
}

/// Whether `mapping` has the block that fills `table`.
fn has_block(mapping: &Remodel, table: Table) -> bool {
    match table {
        Table::Lists | Table::ListNodes | Table::ListNodeLabels => !mapping.lists.is_empty(),
        Table::Resources | Table::Properties => true,
        Table::Representations => mapping.images.is_some(),
        Table::CompoundParts => {
            let mut classes = mapping.classes.iter();
            classes.any(|class| class.member_of.is_some())
        }
        Table::Annotations | Table::AnnotationLinks | Table::AnnotationLinkTargets => mapping.annotations.is_some(),
    }
}

/// The header of the store file of `project`, the project's folder name, built under
/// `mapping`: comment lines that say what the file holds, where its data comes from, and how
/// it is made again.
///
/// Every line is a comment line whatever the mapping holds: a control character in a name, the
/// shortcode or the IIIF base is written as its escape, so it cannot end the comment. The
/// header holds no date, path or other value that differs between runs or machines.
pub fn header(project: &str, mapping: &Remodel) -> String {
    let mut holds: Vec<&str> = mapping.classes.iter().map(|class| class.name.as_str()).collect();
    if mapping.annotations.is_some() {
        holds.push("annotations");
    }
    let holds = holds.join(" + ");
    let shortcode = mapping.shortcode.as_str();
    // A reader of the file learns here that code took part in it.
    let hook = match mapping.hook {
        Some(_) => " and the project's hook",
        None => "",
    };
    let mut lines = vec![
        format!("{project} data ({holds}), generated by cpe-store-build."),
        format!("Source: the cpe-ports snapshot of project {shortcode}."),
        format!("Not from the port: the remodel block of projects/{project}/config.kdl{hook}."),
    ];
    if let Some(images) = &mapping.images {
        lines.push(format!("IIIF: {}", images.iiif_base));
    }
    lines.push(format!(
        "DO NOT hand-edit; regenerate with: just cpe store-build {project} --inplace"
    ));
    lines.iter().map(|line| format!("-- {}\n", comment_text(line))).collect()
}

/// `text` with every control character, a line break above all, written as its escape: the
/// text stays on one line of a comment.
fn comment_text(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if c.is_control() {
            out.extend(c.escape_default());
        } else {
            out.push(c);
        }
    }
    out
}

/// `header`, a blank line, and the `INSERT`s of `tables` in the order given. Every one of
/// `tables` has a row: a multi-row `INSERT` has no empty form.
fn write(store: &Store, header: &str, tables: &[Table]) -> String {
    let mut out = String::from(header);
    out.push('\n');
    for &table in tables {
        match table {
            Table::Lists => insert(&mut out, "INSERT INTO lists (id, name) VALUES", &store.lists, list_cells),
            Table::ListNodes => insert(
                &mut out,
                "INSERT INTO list_nodes (id, list_id, parent_id, seq) VALUES",
                &store.list_nodes,
                list_node_cells,
            ),
            Table::ListNodeLabels => insert(
                &mut out,
                "INSERT INTO list_node_labels (node_id, lang, label) VALUES",
                &store.list_node_labels,
                list_node_label_cells,
            ),
            Table::Resources => insert(
                &mut out,
                "INSERT INTO resources (id, class, ark) VALUES",
                &store.resources,
                resource_cells,
            ),
            Table::Properties => insert(
                &mut out,
                "INSERT INTO properties\n    \
                 (resource_id, name, seq, value_type, value_text, value_lang, value_int, value_real, \
                 date_start, date_end, date_precision, date_display, date_calendar, target_id)\n\
                 VALUES",
                &store.properties,
                property_cells,
            ),
            Table::Representations => insert(
                &mut out,
                "INSERT INTO representations \
                 (resource_id, kind, uri, width, height, alt, attribution, seq) VALUES",
                &store.representations,
                representation_cells,
            ),
            Table::CompoundParts => insert(
                &mut out,
                "INSERT INTO compound_parts (parent_id, child_id, seq) VALUES",
                &store.compound_parts,
                compound_part_cells,
            ),
            Table::Annotations => insert(
                &mut out,
                "INSERT INTO annotations \
                 (id, resource_id, shape, x, y, w, h, points, color, remark, remark_lang, ark) VALUES",
                &store.annotations,
                annotation_cells,
            ),
            Table::AnnotationLinks => insert(
                &mut out,
                "INSERT INTO annotation_links (id, name, name_lang, comment, comment_lang) VALUES",
                &store.annotation_links,
                annotation_link_cells,
            ),
            Table::AnnotationLinkTargets => insert(
                &mut out,
                "INSERT INTO annotation_link_targets (link_id, seq, annotation_id, resource_id) VALUES",
                &store.annotation_link_targets,
                annotation_link_target_cells,
            ),
        }
    }
    out
}

/// One cell of a row, as it is written.
enum Lit<'a> {
    Null,
    Int(i64),
    Real(&'a Real),
    Text(&'a str),
}

fn opt_text(value: &Option<String>) -> Lit<'_> {
    value.as_deref().map_or(Lit::Null, Lit::Text)
}

fn opt_int(value: Option<i64>) -> Lit<'static> {
    value.map_or(Lit::Null, Lit::Int)
}

/// Doubling the apostrophe is the whole escape: SQLite has no backslash escapes in a literal.
fn sql_lit(out: &mut String, lit: &Lit<'_>) {
    match lit {
        Lit::Null => out.push_str("NULL"),
        Lit::Int(value) => out.push_str(&value.to_string()),
        Lit::Real(value) => out.push_str(value.as_str()),
        Lit::Text(value) => {
            out.push('\'');
            out.push_str(&value.replace('\'', "''"));
            out.push('\'');
        }
    }
}

fn push_row(out: &mut String, cells: &[Lit<'_>]) {
    out.push_str("    (");
    for (index, cell) in cells.iter().enumerate() {
        if index > 0 {
            out.push_str(", ");
        }
        sql_lit(out, cell);
    }
    out.push(')');
}

fn insert<T, const N: usize>(out: &mut String, header: &str, rows: &[T], cells: for<'a> fn(&'a T) -> [Lit<'a>; N]) {
    out.push_str(header);
    out.push('\n');
    for (index, row) in rows.iter().enumerate() {
        if index > 0 {
            out.push_str(",\n");
        }
        push_row(out, &cells(row));
    }
    out.push_str(";\n\n");
}

fn list_cells(row: &ListRow) -> [Lit<'_>; 2] {
    [Lit::Text(&row.id), Lit::Text(&row.name)]
}

fn list_node_cells(row: &ListNodeRow) -> [Lit<'_>; 4] {
    [
        Lit::Text(&row.id),
        Lit::Text(&row.list_id),
        opt_text(&row.parent_id),
        Lit::Int(row.seq),
    ]
}

fn list_node_label_cells(row: &ListNodeLabelRow) -> [Lit<'_>; 3] {
    [Lit::Text(&row.node_id), Lit::Text(&row.lang), Lit::Text(&row.label)]
}

fn resource_cells(row: &ResourceRow) -> [Lit<'_>; 3] {
    [Lit::Text(&row.id), Lit::Text(&row.class), opt_text(&row.ark)]
}

fn property_cells(row: &PropertyRow) -> [Lit<'_>; 14] {
    [
        Lit::Text(&row.resource_id),
        Lit::Text(&row.name),
        Lit::Int(row.seq),
        Lit::Text(&row.value_type),
        opt_text(&row.value_text),
        opt_text(&row.value_lang),
        opt_int(row.value_int),
        row.value_real.as_ref().map_or(Lit::Null, Lit::Real),
        opt_text(&row.date_start),
        opt_text(&row.date_end),
        opt_text(&row.date_precision),
        opt_text(&row.date_display),
        opt_text(&row.date_calendar),
        opt_text(&row.target_id),
    ]
}

fn representation_cells(row: &RepresentationRow) -> [Lit<'_>; 8] {
    [
        Lit::Text(&row.resource_id),
        Lit::Text(&row.kind),
        Lit::Text(&row.uri),
        opt_int(row.width),
        opt_int(row.height),
        opt_text(&row.alt),
        opt_text(&row.attribution),
        Lit::Int(row.seq),
    ]
}

fn compound_part_cells(row: &CompoundPartRow) -> [Lit<'_>; 3] {
    [Lit::Text(&row.parent_id), Lit::Text(&row.child_id), Lit::Int(row.seq)]
}

fn annotation_cells(row: &AnnotationRow) -> [Lit<'_>; 12] {
    [
        Lit::Text(&row.id),
        Lit::Text(&row.resource_id),
        Lit::Text(&row.shape),
        Lit::Real(&row.x),
        Lit::Real(&row.y),
        Lit::Real(&row.w),
        Lit::Real(&row.h),
        opt_text(&row.points),
        opt_text(&row.color),
        opt_text(&row.remark),
        opt_text(&row.remark_lang),
        opt_text(&row.ark),
    ]
}

fn annotation_link_cells(row: &AnnotationLinkRow) -> [Lit<'_>; 5] {
    [
        Lit::Text(&row.id),
        Lit::Text(&row.name),
        opt_text(&row.name_lang),
        opt_text(&row.comment),
        opt_text(&row.comment_lang),
    ]
}

fn annotation_link_target_cells(row: &AnnotationLinkTargetRow) -> [Lit<'_>; 4] {
    [
        Lit::Text(&row.link_id),
        Lit::Int(row.seq),
        opt_text(&row.annotation_id),
        opt_text(&row.resource_id),
    ]
}

