    /// The columns the statement that writes `table` names, in its order.
    fn written_columns(table: Table) -> Vec<String> {
        let sql = to_sql_tables(&store(), &full(), OWN, &[table]).expect("the table has a row");
        let statement = format!("INSERT INTO {}", table.name());
        let (_, after_name) = sql.split_once(&statement).expect("the table is written");
        let (_, after_open) = after_name.split_once('(').expect("a column list opens");
        let (columns, _) = after_open.split_once(')').expect("the column list closes");
        columns.split(',').map(|column| column.trim().to_string()).collect()
    }

    /// The columns `table` has in `cpe-store`'s schema, in its order.
    fn schema_columns(connection: &rusqlite::Connection, table: Table) -> Vec<String> {
        let query = format!("SELECT name FROM pragma_table_info('{}') ORDER BY cid", table.name());
        let mut statement = connection.prepare(&query).expect("the query is valid");
        let names = statement
            .query_map([], |row| row.get(0))
            .expect("the query runs")
            .collect::<rusqlite::Result<_>>();
        names.expect("every name is a text")
    }

    /// An empty database under `cpe-store`'s schema.
    fn schema() -> rusqlite::Connection {
        let connection = rusqlite::Connection::open_in_memory().expect("a database opens");
        connection.execute_batch(crate::SCHEMA_SQL).expect("the schema loads");
        connection
    }

    /// A table the schema gains and the row model lacks would stay empty in every built store.
    #[test]
    fn test_table_all_is_every_table_of_the_schema() {
        let connection = schema();
        let mut statement = connection
            .prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'")
            .expect("the query is valid");
        let mut in_schema: Vec<String> = statement
            .query_map([], |row| row.get(0))
            .expect("the query runs")
            .collect::<rusqlite::Result<_>>()
            .expect("every name is a text");
        in_schema.sort();
        let mut ours = Table::ALL.map(Table::name);
        ours.sort_unstable();

        assert_eq!(in_schema, ours);
    }

    /// A column the schema gains and no writer names would load as NULL in every row.
    #[test]
    fn test_to_sql_writes_every_column_of_the_schema_in_its_order() {
        let connection = schema();

        for table in Table::ALL {
            let mut in_schema = schema_columns(&connection, table);
            if table == Table::Representations {
                // SQLite assigns it.
                in_schema.retain(|column| column != "id");
            }

            assert!(!in_schema.is_empty(), "{} has no column", table.name());
            assert_eq!(
                written_columns(table),
                in_schema,
                "{}: the writer's columns are not the schema's. Add the column to the table's \
                 row in src/store.rs and to its statement and cells in src/sql.rs",
                table.name()
            );
        }
    }

    #[test]
    fn test_to_sql_empty_table_is_refused_by_name() {
        let store = Store { compound_parts: Vec::new(), ..store() };

        let error = to_sql(&store, &full(), OWN).expect_err("compound_parts is empty");

        assert_eq!(error, EmptyTable(Table::CompoundParts));
        assert_eq!(error.to_string(), "table compound_parts has no row");
    }
